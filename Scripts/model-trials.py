def sitemap(data):
    newest = max(t["date"] for t in data["trials"])
    text = SITEMAP.read_text()
    line = f"  <url><loc>{URL}</loc><lastmod>{newest}</lastmod></url>"
    pattern = re.compile(rf"^  <url><loc>{re.escape(URL)}</loc>.*$", re.M)
    if pattern.search(text):
        return pattern.sub(line, text)
    return text.replace("</urlset>", line + "\n</urlset>")


def main():
    data = load()
    outputs = {MARKDOWN: markdown(data), PAGE: page(data), SITEMAP: sitemap(data)}
    if "--check" in sys.argv:
        stale = [p.relative_to(ROOT) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            raise SystemExit(f"stale, run make model-trials: {', '.join(map(str, stale))}")
        return
    for path, text in outputs.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
